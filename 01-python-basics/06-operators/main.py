# Arithmetic Operators

number1 = 20
number2 = 5

addition = number1 + number2
print(addition)

subtraction = number1 - number2
print(subtraction)

multiplication = number1 * number2
print(multiplication)

division = number1 / number2
print(division)

print(20 // 3)
print(20 % 3)
print(3 ** 2)


# Assignment Operators

points = 20
points += 10
print(points)

price = 100
price -= 20
print(price)

total = 10
total *= 4
print(total)

amount = 50
amount /= 5
print(amount)


# Comparison Operators

age = 18

print(age == 18)
print(age != 10)
print(age > 15)
print(age < 20)
print(age >= 18)
print(age <= 18)


# Logical Operators

print(age > 18 and age < 30)
print(age < 18 or age > 30)
print(not age > 18)
